        val q = QrCode.encode(text)!!
        assertEquals(size, q.size, text)
        val got = (0 until q.size).map { r -> (0 until q.size).joinToString("") { c -> if (q.isDark(r, c)) "1" else "0" } }
        assertEquals(rows, got, text)
    }

